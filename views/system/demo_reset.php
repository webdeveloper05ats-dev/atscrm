if (!function_exists('demoResetTableColumns')) {
    function demoResetTableColumns(PDO $pdo, string $table): array
    {
        static $cache = [];
        if (isset($cache[$table])) {
            return $cache[$table];
        }
        try {
            $safeTable = '`' . str_replace('`', '``', $table) . '`';
            $rows = $pdo->query('SHOW COLUMNS FROM ' . $safeTable)->fetchAll(PDO::FETCH_ASSOC) ?: [];
            $cache[$table] = $rows;
            return $rows;
        } catch (Throwable $e) {
            $cache[$table] = [];
            return [];
        }
    }
}

if (!function_exists('demoResetFirstEnumValue')) {
    function demoResetFirstEnumValue(string $type): string
    {
        if (!preg_match("/^enum\((.*)\)$/i", $type, $m)) {
            return '';
        }
        $raw = trim((string)($m[1] ?? ''));
        if ($raw === '') {
            return '';
        }
        $parts = str_getcsv($raw, ',', "'");
        return trim((string)($parts[0] ?? ''));
    }
}

if (!function_exists('demoResetFallbackValue')) {
    function demoResetFallbackValue(array $col)
    {
        $type = strtolower((string)($col['Type'] ?? ''));
        if (strpos($type, 'int') !== false || strpos($type, 'decimal') !== false || strpos($type, 'float') !== false || strpos($type, 'double') !== false) {
            return 0;
        }
        if (strpos($type, 'datetime') !== false || strpos($type, 'timestamp') !== false) {
            return date('Y-m-d H:i:s');
        }
        if ($type === 'date' || strpos($type, 'date') !== false) {
            return date('Y-m-d');
        }
        if ($type === 'time' || strpos($type, 'time') !== false) {
            return date('H:i:s');
        }
        if (strpos($type, 'json') !== false) {
            return '{}';
        }
        if (strpos($type, 'enum(') === 0) {
            $first = demoResetFirstEnumValue($type);
            return $first !== '' ? $first : '';
        }
        return '';
    }
}

if (!function_exists('demoResetInsertAdaptive')) {
    function demoResetInsertAdaptive(PDO $pdo, string $table, array $preferred = []): int
    {
        $columns = demoResetTableColumns($pdo, $table);
        if (empty($columns)) {
            return 0;
        }

        $row = [];
        foreach ($columns as $col) {
            $field = (string)($col['Field'] ?? '');
            if ($field === '') {
                continue;
            }
            $isAuto = stripos((string)($col['Extra'] ?? ''), 'auto_increment') !== false;
            if ($isAuto) {
                continue;
            }

            if (array_key_exists($field, $preferred)) {
                $row[$field] = $preferred[$field];
                continue;
            }

            if (($col['Default'] ?? null) !== null) {
                continue;
            }

            $nullable = strtoupper((string)($col['Null'] ?? 'NO')) === 'YES';
            if ($nullable) {
                continue;
            }

            $row[$field] = demoResetFallbackValue($col);
        }

        if (empty($row)) {
            return 0;
        }

        $safeTable = '`' . str_replace('`', '``', $table) . '`';
        $fields = array_keys($row);
        $fieldSql = implode(',', array_map(static function ($f) {
            return '`' . str_replace('`', '``', $f) . '`';
        }, $fields));
        $valueSql = implode(',', array_fill(0, count($fields), '?'));

        $st = $pdo->prepare('INSERT INTO ' . $safeTable . ' (' . $fieldSql . ') VALUES (' . $valueSql . ')');
        $st->execute(array_values($row));
        return (int)$pdo->lastInsertId();
    }
}

