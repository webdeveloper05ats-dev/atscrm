    if (function_exists('crmTableExists') && crmTableExists($pdo, $table)) {
        $existingResetTables[] = $table;
    }
}

if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['run_demo_reset'])) {
    $token = (string)($_POST['csrf_token'] ?? '');
    $confirmText = trim((string)($_POST['confirm_text'] ?? ''));
    $acknowledge = isset($_POST['confirm_irreversible']) ? (string)$_POST['confirm_irreversible'] : '';
    $reseedAfterReset = isset($_POST['reseed_demo_data']) ? (string)$_POST['reseed_demo_data'] : '';

    if (!function_exists('verifyCSRF') || !verifyCSRF($token)) {
        $_SESSION['demo_reset_flash'] = ['type' => 'error', 'text' => 'Invalid request token. Please retry.'];
        header('Location: index.php?page=system/demo_reset');
        exit;
    }

    if (strtoupper($confirmText) !== 'RESET DEMO') {
        $_SESSION['demo_reset_flash'] = ['type' => 'error', 'text' => 'Type exactly RESET DEMO to proceed.'];
        header('Location: index.php?page=system/demo_reset');
        exit;
    }

    if ($acknowledge !== '1') {
        $_SESSION['demo_reset_flash'] = ['type' => 'error', 'text' => 'Please confirm that this action cannot be undone.'];
        header('Location: index.php?page=system/demo_reset');
        exit;
    }

    if (empty($existingResetTables)) {
        $_SESSION['demo_reset_flash'] = ['type' => 'error', 'text' => 'No reset tables were found in this database.'];
        header('Location: index.php?page=system/demo_reset');
        exit;
    }

    $resetDone = 0;
    $reseedSummary = [];
    try {
        @set_time_limit(120);
        $pdo->beginTransaction();
        $pdo->exec('SET FOREIGN_KEY_CHECKS = 0');

        foreach ($existingResetTables as $table) {
            $safeTable = '`' . str_replace('`', '``', $table) . '`';
            $pdo->exec('TRUNCATE TABLE ' . $safeTable);
            $resetDone++;
        }

        if ($reseedAfterReset === '1') {
            $reseedSummary = demoResetRunReseed($pdo);
        }

        $pdo->exec('SET FOREIGN_KEY_CHECKS = 1');
        $pdo->commit();

        if (function_exists('crmAuditInsert')) {
            $auditAction = 'Demo reset executed. Cleared tables: ' . implode(', ', $existingResetTables);
            if ($reseedAfterReset === '1') {
                $createdCount = 0;
                foreach ($reseedSummary as $id) {
                    if ((int)$id > 0) {
                        $createdCount++;
                    }
                }
                $auditAction .= '. Reseed: enabled, created rows: ' . $createdCount;
            }
            crmAuditInsert($pdo, [
                'table_name' => 'system',
                'record_id' => 0,
                'action' => $auditAction,
            ]);
        }

        $msg = 'Demo reset completed. Cleared ' . $resetDone . ' table(s).';
        if ($reseedAfterReset === '1') {
            $createdCount = 0;
            foreach ($reseedSummary as $id) {
                if ((int)$id > 0) {
                    $createdCount++;
                }
            }
            $msg .= ' Reseed enabled: ' . $createdCount . ' sample row group(s) created.';
        }
        $_SESSION['demo_reset_flash'] = ['type' => 'success', 'text' => $msg];
        header('Location: index.php?page=system/demo_reset');
        exit;
    } catch (Throwable $e) {
        try {
            if ($pdo->inTransaction()) {
                $pdo->rollBack();
            }
            $pdo->exec('SET FOREIGN_KEY_CHECKS = 1');
        } catch (Throwable $inner) {
            // no-op
        }

        $_SESSION['demo_reset_flash'] = ['type' => 'error', 'text' => 'Demo reset failed: ' . $e->getMessage()];
        header('Location: index.php?page=system/demo_reset');
        exit;
    }
}
